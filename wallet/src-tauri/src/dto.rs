//! Public IPC views only. Secret-bearing storage records deliberately do not derive TS.
use crate::model::{Center, Draft, LoginTask, TrustedApp};
use crypto_sso_identity_api::{Claims, EnrollmentView};
use serde::Serialize;
use ts_rs::TS;

#[derive(Serialize, TS)]
pub struct WalletStatus {
    pub initialized: bool,
    pub unlocked: bool,
    pub epoch: u64,
    pub version: u8,
}
#[derive(Serialize, TS)]
pub struct CredentialView {
    pub id: String,
    pub center_id: String,
    pub issuer_id: String,
    #[ts(type = "Record<string, string>")]
    pub claims: Claims,
    pub saved_at: u64,
}
#[derive(Serialize, TS)]
pub struct LocalEnrollmentView {
    pub id: String,
    pub center_id: String,
    #[ts(type = "Record<string, string>")]
    pub claims: Claims,
    pub view: Option<EnrollmentView>,
    pub local_state: String,
    pub error: Option<String>,
    pub synced_at: Option<u64>,
    pub recovery_saved: bool,
}
#[derive(Serialize, TS)]
pub struct DisclosurePlan {
    pub task: LoginTask,
    pub app: TrustedApp,
    pub state: String,
    pub expires_at: u64,
    pub required_claims: Vec<String>,
    pub missing_claims: Vec<String>,
    pub credential: Option<CredentialView>,
    pub center_id: Option<String>,
}
pub fn declarations() -> String {
    let declarations = [
        WalletStatus::decl(),
        Center::decl(),
        Draft::decl(),
        TrustedApp::decl(),
        LoginTask::decl(),
        CredentialView::decl(),
        LocalEnrollmentView::decl(),
        DisclosurePlan::decl(),
    ];
    format!(
        "// Generated by cargo run -p wallet --example export_ipc.\nimport type {{ ServiceInfo, EnrollmentView }} from '@crypto-sso/identity-api-types';\n{}\n",
        declarations
            .join("\n")
            .replace("type ", "export type ")
            .replace("bigint", "number")
    )
}
